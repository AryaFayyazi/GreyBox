#!/usr/bin/env python
"""Live v2 benchmark: conversations for training and evaluating Grey Box Live readouts as a TOOL.

Each item is a list of user turns (assistant turns are generated by each model at run time, scripts/36) with labels
for the LATEST user message.
  train  single-turn L2 dev contexts + 600 multi-turn conversations from L2 dev pools and ToxicChat train
  eval   - toxicchat: 800 real user prompts from ToxicChat test (200 toxic, 600 non-toxic; real traffic)
         - xstest:    450 XSTest prompts (250 safe-but-scary-sounding, 200 unsafe contrasts)
         - multiturn: 400 conversations from L2 confirm pools + ToxicChat test with switch patterns
                      B>B, H>B (carry-over), B>H, H>B>B, B>H>B; label = latest message
Output: /data/models/graybox_ws/outputs/livebench/items.parquet
"""
from pathlib import Path

import numpy as np
import pandas as pd
from datasets import load_dataset

OUT = Path("/data/models/graybox_ws/outputs/livebench")
L2 = Path("/data/models/graybox_ws/outputs/l2")
rng = np.random.default_rng(0)


def main():
    C = pd.read_parquet(L2 / "contexts.parquet")
    tc_tr = load_dataset("lmsys/toxic-chat", "toxicchat0124", split="train").to_pandas()
    tc_te = load_dataset("lmsys/toxic-chat", "toxicchat0124", split="test").to_pandas()
    xs = load_dataset("natolambert/xstest-v2-copy", split="prompts").to_pandas()
    for d in (tc_tr, tc_te):
        d["user_input"] = d.user_input.str.strip()
        d.drop(d[(d.user_input.str.len() < 5) | (d.user_input.str.len() > 1500)].index, inplace=True)

    def pools(split, tc):
        c = C[C.split == split]
        H = list(c[c.source == "harmful"].text) + list(tc[tc.toxicity == 1].user_input)
        B = list(c[c.source.isin(["benign", "gsm8k", "wiki", "boolq", "sst2"])].text) + list(tc[tc.toxicity == 0].user_input)
        return H, B

    rows = []
    for _, r in C[C.split == "dev"].iterrows():
        rows.append({"split": "train", "kind": "single", "turns": [r.text], "harmful": int(r.source == "harmful"),
                     "pattern": "H" if r.source == "harmful" else "B", "source": r.source})

    def convs(n, H, B, split, kind):
        pats = ["B>B", "H>B", "B>H", "H>B>B", "B>H>B"]
        for i in range(n):
            p = pats[i % len(pats)]
            turns = [H[rng.integers(len(H))] if s == "H" else B[rng.integers(len(B))] for s in p.split(">")]
            rows.append({"split": split, "kind": kind, "turns": turns, "harmful": int(p.split(">")[-1] == "H"),
                         "pattern": p, "source": "mixed"})

    H, B = pools("dev", tc_tr)
    convs(600, H, B, "train", "multiturn")
    tox = tc_te[tc_te.toxicity == 1].sample(200, random_state=0)
    non = tc_te[tc_te.toxicity == 0].sample(600, random_state=0)
    for d, lab in ((tox, 1), (non, 0)):
        for _, r in d.iterrows():
            rows.append({"split": "eval", "kind": "toxicchat", "turns": [r.user_input], "harmful": lab,
                         "pattern": "H" if lab else "B", "source": "toxicchat", "jailbreak": int(r.jailbreaking)})
    for _, r in xs.iterrows():
        unsafe = int(str(r.type).startswith("contrast"))
        rows.append({"split": "eval", "kind": "xstest", "turns": [r.prompt], "harmful": unsafe,
                     "pattern": "H" if unsafe else "B", "source": f"xstest:{r.type}"})
    H, B = pools("confirm", tc_te.drop(tox.index).drop(non.index))
    convs(400, H, B, "eval", "multiturn")
    df = pd.DataFrame(rows)
    df["jailbreak"] = df.get("jailbreak", pd.Series(dtype=float)).fillna(0).astype(int)
    df["id"] = [f"lb{i}" for i in range(len(df))]
    OUT.mkdir(parents=True, exist_ok=True)
    df.to_parquet(OUT / "items.parquet")
    print(df.groupby(["split", "kind", "pattern"]).size().to_string())
    print("total", len(df), "turns", int(df.turns.map(len).sum()))


if __name__ == "__main__":
    main()
