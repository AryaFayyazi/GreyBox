#!/usr/bin/env python
"""Write paper/g14_numbers.tex from results/t1/g14_decision_grey_box.json, so the paper quotes G14 only through macros.
python paper/make_g14_numbers.py"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R = json.loads((ROOT / "results/t1/g14_decision_grey_box.json").read_text())
N = {"gemma4": "Gemma-4", "gptoss20b": "gpt-oss", "qwen38": "Qwen3.8", "museglimmer": "Muse-Glimmer", "claude": "Closed-A"}
OPEN = [a for a in ("gemma4", "gptoss20b", "qwen38", "museglimmer") if a in R]


def f3(x):
    return f"{x:.3f}".replace("-", "$-$")


def ci(v):
    return f"{'+' if v[0] >= 0 else ''}{f3(v[0])} [{f3(v[1])}, {f3(v[2])}]"


m = {}
m["GFtWhite"] = ", ".join(f"{N[a]} {f3(R[a]['within']['white_box'])}" for a in OPEN)
m["GFtGrey"] = ", ".join(f"{N[a]} {f3(R[a]['within']['grey_box'])}" for a in OPEN)
m["GFtCross"] = ", ".join(f"{N[a]} {f3(R[a]['within']['others_grey_box'])}" for a in OPEN)
m["GFtPone"] = ci(R["P1_grey_minus_white_mean"])
m["GFtPtwo"] = ci(R["P2_others_grey_minus_own_white_mean"])
m["GFtPthree"] = ci(R["P3_answers_add_to_reader_mean"])
if "claude" in R:
    m["GFtClosedA"] = f3(R["claude"]["restart_within"]) if "restart_within" in R["claude"] else "--"
lines = [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in m.items()]
(ROOT / "paper/g14_numbers.tex").write_text("% generated by paper/make_g14_numbers.py from results/t1/g14_decision_grey_box.json\n" + "\n".join(lines) + "\n")
print("\n".join(lines))
