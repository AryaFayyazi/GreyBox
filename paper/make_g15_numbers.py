#!/usr/bin/env python
"""Write paper/g15_numbers.tex from results/t1/g15_training_free.json (the paper quotes G15 only through these macros).
python paper/make_g15_numbers.py"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R = json.loads((ROOT / "results/t1/g15_training_free.json").read_text())
N = {"gemma4": "Gemma-4", "gptoss20b": "gpt-oss", "qwen38": "Qwen3.8", "museglimmer": "Muse-Glimmer"}
OPEN = [a for a in N if a in R]


def f3(x):
    return f"{x:.3f}".replace("-", "$-$")


def ci(v):
    return f"{'+' if v[0] >= 0 else ''}{f3(v[0])} [{f3(v[1])}, {f3(v[2])}]"


E = R["endpoints"]
m = {"GFtFixed": ", ".join(f"{N[a]} {f3(R[a]['within']['mean8'])}" for a in OPEN),
     "GFtTrainedWB": ", ".join(f"{N[a]} {f3(R[a]['within']['white'])}" for a in OPEN),
     "GFtTone": ci(R["T1_mean8_minus_complies"]), "GFtTtwo": ci(R["T2_mean8_minus_white_box"])}
if "claude" in R:
    c = R["claude"]
    m["GFtClosedAFixed"] = f"{f3(c['restart_mean8'])} [{f3(c['restart_mean8_ci'][0])}, {f3(c['restart_mean8_ci'][1])}]"
t2 = R["T2_mean8_minus_white_box"]
m["GFtIntro"] = (f"as well as a probe trained on its true hidden states (mean difference {ci(t2)})" if E.get("T2_lower_gt_-0.05")
                 else f"short of a probe trained on its true hidden states (mean difference {ci(t2)})")
lines = [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in m.items()]
(ROOT / "paper/g15_numbers.tex").write_text("% generated by paper/make_g15_numbers.py from results/t1/g15_training_free.json\n" + "\n".join(lines) + "\n")
print("\n".join(lines))
